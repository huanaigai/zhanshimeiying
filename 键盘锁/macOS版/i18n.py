LANGUAGE_ORDER = ("zh", "en")


def t(lang, key, **kwargs):
    """取一条文案；缺失时回退到中文，再回退到 key 本身。"""
    table = STRINGS.get(lang) or STRINGS["zh"]
    text = table.get(key)
    if text is None:
        text = STRINGS["zh"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


def next_language(lang):
    """在中/英之间切换。"""
    try:
        index = LANGUAGE_ORDER.index(lang)
    except ValueError:
        return LANGUAGE_ORDER[0]
    return LANGUAGE_ORDER[(index + 1) % len(LANGUAGE_ORDER)]
